/**
 * Resolve a state name from Excel to an SVG map ID.
 * Handles trimming, lowercasing, and common typos.
 */
export function resolveStateId(rawName: string): string | null {
  if (!rawName) return null;
  const normalized = rawName.trim().toLowerCase().replace(/\s+/g, ' ');
  return STATE_NAME_TO_SVG_ID[normalized] ?? null;
}
